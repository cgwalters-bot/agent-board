// Checks the built site (`just site-build`, which `just site-test` runs
// first): the LLM notice is the page banner exactly where the page's
// source has the notice, and is not also left in the page body.
import assert from "node:assert/strict";
import { readFileSync, readdirSync } from "node:fs";
import { test } from "node:test";
import { DOCS, LLM_NOTICE, NOTICE_LINK, PAGES, llmNotice, pageId } from "./links.mjs";

const root = new URL("..", import.meta.url);
const files = [...Object.keys(PAGES), ...readdirSync(new URL(DOCS, root)).filter((n) => n.endsWith(".md")).map((n) => `${DOCS}${n}`)];

function text(html) {
  return html
    .replace(/<[^>]*>/g, "")
    .replace(/&#(\d+);/g, (_, n) => String.fromCodePoint(Number(n)))
    .replace(/&#x([0-9a-f]+);/gi, (_, n) => String.fromCodePoint(parseInt(n, 16)))
    .replace(/&quot;/g, '"')
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&amp;/g, "&")
    .replace(/\s+/g, " ")
    .trim();
}

test("LLM notice banner", () => {
  const plain = text(LLM_NOTICE.replace(`[${NOTICE_LINK.text}](${NOTICE_LINK.href})`, NOTICE_LINK.text));
  const seen = { with: 0, without: 0 };
  for (const file of files) {
    const id = pageId(file);
    const html = readFileSync(new URL(`site/dist/${id === "" ? "" : `${id}/`}index.html`, root), "utf8");
    const banners = [...html.matchAll(/<div[^>]*\bdata-llm-notice\b[^>]*>([\s\S]*?)<\/div>/g)];
    const notice = llmNotice(readFileSync(new URL(file, root), "utf8"));
    if (notice === null) {
      seen.without++;
      assert.equal(banners.length, 0, `${file}: banner without a notice in the source`);
      continue;
    }
    seen.with++;
    assert.equal(banners.length, 1, `${file}: one banner`);
    assert.equal(text(banners[0][1]), `${plain}${notice && ` ${notice}`}`, `${file}: banner text`);
    assert.ok(banners[0][1].includes(`href="${NOTICE_LINK.href}"`), `${file}: banner link`);
    // The banner is the only place the notice appears: no body blockquote.
    assert.equal(text(html).split(plain).length - 1, 1, `${file}: notice in the body too`);
    assert.doesNotMatch(html, /<blockquote>\s*<p>This text was generated by an LLM/, `${file}: notice blockquote in the body`);
  }
  // The landing page has the notice; documents written by hand (today
  // docs/apps.md, among others) have none.
  assert.ok(llmNotice(readFileSync(new URL("site/index.md", root), "utf8")) !== null, "landing page notice");
  assert.ok(seen.with > 0 && seen.without > 0, `pages with and without the notice: ${JSON.stringify(seen)}`);
});
