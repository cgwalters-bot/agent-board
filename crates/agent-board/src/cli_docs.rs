//! The Markdown CLI reference (docs/cli.md), rendered from the clap
//! definitions so no document keeps its own list of commands.
//!
//! A walk over `clap::Command` rather than the clap-markdown crate: it is
//! short, and controls the output the documentation site renders
//! (headings, anchors, no HTML footer).

use clap::{Arg, Command};
use std::fmt::Write;

/// The command that regenerates the committed reference.
pub const REGENERATE: &str = "just cli-docs";

/// Arguments clap adds to every command; documenting them on each is noise.
const BUILTIN_ARGS: &[&str] = &["help", "version"];

/// The standard notice a generated document starts with, under its title
/// (`LLM_NOTICE` in site/links.mjs, which turns it into the page banner):
/// the help strings this renders were written with LLMs.
const LLM_NOTICE: &str = "> This text was generated by an LLM \
    ([how cgwalters uses LLMs](https://github.com/cgwalters/cgwalters#llms)). \
    cgwalters has not reviewed it yet.";

pub fn markdown(mut root: Command) -> String {
    // Building propagates global options and sets each command's full name.
    root.build();
    let mut out = String::new();
    out.push_str("# CLI reference\n\n");
    let _ = writeln!(out, "{LLM_NOTICE}\n");
    let _ = writeln!(
        out,
        "Generated from `{name}`'s own help by `{name} help-markdown`; \
         regenerate it with `{REGENERATE}` rather than editing it. \
         The `gh-agent-board` binary is the same CLI, run as `gh agent-board`.",
        name = root.get_name(),
    );
    command(&mut out, &root, true);
    out
}

fn command(out: &mut String, cmd: &Command, root: bool) {
    let name = cmd.get_bin_name().unwrap_or(cmd.get_name());
    let _ = writeln!(out, "\n## {name}\n");
    if let Some(about) = cmd.get_long_about().or(cmd.get_about()) {
        let _ = writeln!(out, "{}\n", about.to_string().trim_end());
    }
    let usage = cmd.clone().render_usage().to_string();
    let usage = usage.trim_start_matches("Usage:").trim();
    let _ = writeln!(out, "```text\n{usage}\n```");

    let subcommands: Vec<&Command> = visible_subcommands(cmd).collect();
    if !subcommands.is_empty() {
        out.push_str("\nCommands:\n\n");
        for sub in &subcommands {
            let full = sub.get_bin_name().unwrap_or(sub.get_name());
            let _ = write!(out, "- [`{}`](#{})", sub.get_name(), anchor(full));
            if let Some(about) = sub.get_about() {
                let _ = write!(out, ": {about}");
            }
            out.push('\n');
        }
    }

    // Globals are documented once, on the root; clap copies them to every
    // subcommand when it builds.
    let args = || {
        cmd.get_arguments().filter(|arg| {
            !arg.is_hide_set()
                && !BUILTIN_ARGS.contains(&arg.get_id().as_str())
                && (root || !arg.is_global_set())
        })
    };
    let positionals: Vec<&Arg> = args().filter(|arg| arg.is_positional()).collect();
    let options: Vec<&Arg> = args().filter(|arg| !arg.is_positional()).collect();
    arguments(out, "Arguments", &positionals);
    arguments(
        out,
        if root { "Global options" } else { "Options" },
        &options,
    );

    for sub in subcommands {
        command(out, sub, false);
    }
}

fn visible_subcommands(cmd: &Command) -> impl Iterator<Item = &Command> {
    // clap's generated `help` subcommand is not one of ours.
    cmd.get_subcommands()
        .filter(|sub| !sub.is_hide_set() && sub.get_name() != "help")
}

fn arguments(out: &mut String, title: &str, args: &[&Arg]) {
    if args.is_empty() {
        return;
    }
    let _ = writeln!(out, "\n{title}:\n");
    for arg in args {
        let _ = write!(out, "- `{}`", signature(arg));
        if let Some(help) = arg.get_long_help().or(arg.get_help()) {
            // Continuation lines stay inside the list item.
            let help = help.to_string();
            let _ = write!(out, ": {}", help.trim_end().replace('\n', "\n  "));
        }
        let possible: Vec<String> = arg
            .get_possible_values()
            .iter()
            .filter(|value| !value.is_hide_set())
            .map(|value| format!("`{}`", value.get_name()))
            .collect();
        if !possible.is_empty() && !arg.is_hide_possible_values_set() {
            let _ = write!(out, " (possible values: {})", possible.join(", "));
        }
        // A flag's implicit `false` says nothing; clap's help omits it too.
        let defaults: Vec<String> = arg
            .get_default_values()
            .iter()
            .map(|value| match value.to_string_lossy() {
                empty if empty.is_empty() => "`\"\"`".to_owned(),
                value => format!("`{value}`"),
            })
            .collect();
        if !defaults.is_empty()
            && !arg.is_hide_default_value_set()
            && arg.get_action().takes_values()
        {
            let _ = write!(out, " (default: {})", defaults.join(", "));
        }
        out.push('\n');
    }
}

/// How the argument is written: `-R, --repo <REPO>`, `--apply`, `<ITEM>`.
fn signature(arg: &Arg) -> String {
    let values = || -> Vec<String> {
        match arg.get_value_names() {
            Some(names) => names.iter().map(|name| format!("<{name}>")).collect(),
            None => vec![format!("<{}>", arg.get_id().as_str().to_uppercase())],
        }
    };
    if arg.is_positional() {
        let mut values = values().join(" ");
        if matches!(arg.get_num_args(), Some(range) if range.max_values() > 1) {
            values.push_str("...");
        }
        return values;
    }
    let mut names = Vec::new();
    if let Some(short) = arg.get_short() {
        names.push(format!("-{short}"));
    }
    if let Some(long) = arg.get_long() {
        names.push(format!("--{long}"));
    }
    let mut signature = names.join(", ");
    if arg.get_action().takes_values() {
        signature.push(' ');
        signature.push_str(&values().join(" "));
    }
    signature
}

/// The heading anchor the site and the forge give `## {heading}`: lower
/// case, spaces to `-` (command names have no other punctuation).
fn anchor(heading: &str) -> String {
    heading.to_lowercase().replace(' ', "-")
}
